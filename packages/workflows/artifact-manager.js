import fs from "node:fs/promises";
import crypto from "node:crypto";
import { buildArtifactLocation, getArtifactDir } from "../shared/artifact-paths.js";
import {
  formatApprovalSummaryList,
  formatListOrNone,
  formatObjectFieldList,
  renderArtifactCoverageLine,
  renderArtifactDocument,
  renderLatestPlanRunSummaryLine,
  renderRecentArtifactPathLine
} from "../shared/artifact-render.js";

export class WorkflowArtifactManager {
  constructor({ config, stateStore }) {
    this.config = config;
    this.stateStore = stateStore;
    this.artifactDir = getArtifactDir(config, "agent-workflows");
  }

  async exportWorkflowArtifact({ workflowId, title }) {
    const workflow = workflowId
      ? await this.stateStore.getWorkflowBundle(workflowId)
      : await getLatestWorkflowBundle(this.stateStore);
    const dashboard = await this.stateStore.getDashboardSummary();

    if (!workflow) {
      throw new Error("No workflow record available to export.");
    }

    const createdAt = new Date().toISOString();
    const safeTitle = slugify(title || workflow.title || "workflow").slice(0, 80) || "workflow";
    const timestamp = createdAt.replace(/[:]/g, "-").replace(/\..+$/, "");
    const { absolutePath, storedPath } = buildArtifactLocation(this.config, "agent-workflows", `${timestamp}-${safeTitle}.md`);

    await fs.mkdir(this.artifactDir, { recursive: true });
    await fs.writeFile(absolutePath, renderWorkflowDocument({ workflow, dashboard, title, createdAt }), "utf8");

    const record = {
      id: `workflowartifact_${crypto.randomUUID()}`,
      createdAt,
      workflowId: workflow.id,
      title: title || workflow.title || "workflow",
      status: workflow.status,
      path: storedPath
    };

    await this.stateStore.saveWorkflowArtifact(record);
    return record;
  }
}

function renderWorkflowDocument({ workflow, dashboard, title, createdAt }) {
  return renderArtifactDocument({
    title: title || workflow.title || "workflow",
    metadata: [
      `Generated at: ${createdAt}`,
      `Workflow id: ${workflow.id}`,
      `Status: ${workflow.status}`,
      `Status reasons: ${formatStatusReasons(workflow.statusReasons || [])}`,
      `Goal: ${workflow.goal || "(none)"}`
    ],
    sections: [
      {
        title: "Linked Records",
        lines: [
          `- Plan run: ${workflow.planRunId}`,
          `- Plan artifact: ${workflow.planArtifactId}`,
          `- Approval requests: ${formatListOrNone((workflow.approvalRequestIds || []))}`,
          ...workflow.reviewIds.map((id) => `- Review: ${id}`),
          ...workflow.reviewArtifactIds.map((id) => `- Review artifact: ${id}`),
          ...(workflow.traceIds || []).map((id) => `- Trace: ${id}`),
          ...(workflow.traceArtifactId ? [`- Trace artifact: ${workflow.traceArtifactId}`] : [])
        ]
      },
      {
        title: "Summaries",
        lines: [
          renderLatestPlanRunSummaryLine(workflow.planRun).replace("Latest plan run", "Plan run"),
          `- Workflow approval summaries: ${formatApprovalSummaryList(workflow.approvalRequests || [])}`,
          `- Workflow status reasons: ${formatStatusReasons(workflow.statusReasons || [])}`,
          `- Recent approval summaries: ${formatApprovalSummaryList(dashboard?.recentApprovalRequests || [])}`,
          ...(workflow.reviews || []).map((review) => `- ${review.kind} review: ${review.status} (${review.summary})`),
          ...(workflow.reviewArtifacts || []).map((artifact) => `- Review artifact file: ${artifact.path}`),
          ...(workflow.traceArtifacts || []).map((artifact) => `- Trace artifact file: ${artifact.path} (${artifact.traceCount} traces)`),
          renderArtifactCoverageLine(workflow.dashboardSummary?.artifactCoverage),
          renderRecentArtifactPathLine("workflow artifact", workflow.workflowArtifacts || []),
          renderRecentArtifactPathLine("dashboard artifact", workflow.dashboardArtifacts || []),
          renderRecentArtifactPathLine("bundle-index artifact", workflow.bundleIndexArtifacts || [])
        ]
      }
    ],
    notes: [
      "This file was generated by the coding-agent workflow artifact exporter.",
      "Export a fresh workflow artifact after rerunning the workflow if the execution evidence changes."
    ]
  });
}

async function getLatestWorkflowBundle(stateStore) {
  const latest = (await stateStore.listWorkflowRuns())[0] || null;
  if (!latest) {
    return null;
  }
  return stateStore.getWorkflowBundle(latest.id);
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function formatStatusReasons(reasons) {
  if (!reasons || reasons.length === 0) {
    return "(none)";
  }
  return reasons.map((item) => `${item.code || item.category}: ${item.message}`).join(" | ");
}
