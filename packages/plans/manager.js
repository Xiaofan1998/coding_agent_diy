import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { buildArtifactLocation, getArtifactDir } from "../shared/artifact-paths.js";
import {
  formatObjectFieldList,
  formatWorkflowLabel,
  renderArtifactDocument,
  renderLatestPlanRunSummaryLine,
  renderLatestWorkflowSummaryLine
} from "../shared/artifact-render.js";

export class PlanArtifactManager {
  constructor({ config, stateStore }) {
    this.config = config;
    this.stateStore = stateStore;
    this.artifactDir = getArtifactDir(config, "agent-plans");
  }

  async exportActivePlan({ title, goal, workflowId = "" }) {
    const planItems = await this.stateStore.getPlanItems();
    const latestPlanRun = (await this.stateStore.listPlanRuns())[0] || null;
    const latestWorkflow = (await this.stateStore.listWorkflowRuns())[0] || null;
    const linkedWorkflow = workflowId ? await this.stateStore.getWorkflowRun(workflowId) : null;
    const linkedWorkflowArtifacts = workflowId ? await this.stateStore.listWorkflowArtifactsByWorkflow(workflowId) : [];
    const objective = goal?.objective || title || "Active plan";
    const safeTitle = slugify(title || objective).slice(0, 80) || "active-plan";
    const createdAt = new Date().toISOString();
    const timestamp = createdAt.replace(/[:]/g, "-").replace(/\..+$/, "");
    const { absolutePath, storedPath } = buildArtifactLocation(this.config, "agent-plans", `${timestamp}-${safeTitle}.md`);

    await fs.mkdir(this.artifactDir, { recursive: true });
    await fs.writeFile(
      absolutePath,
      renderPlanDocument({
        title: title || objective,
        objective,
        goal,
        planItems,
        createdAt,
        latestPlanRun,
        latestWorkflow,
        linkedWorkflow,
        linkedWorkflowArtifacts
      }),
      "utf8"
    );

    const record = {
      id: `planartifact_${crypto.randomUUID()}`,
      createdAt,
      title: title || objective,
      objective,
      path: storedPath,
      itemCount: planItems.length,
      workflowId: workflowId || null
    };

    await this.stateStore.savePlanArtifact(record);
    return record;
  }

  async createSuggestedPlan({ objective, goal, repoSnapshot, skills = [] }) {
    const planItems = buildSuggestedPlanItems({ objective, repoSnapshot });
    await this.stateStore.updatePlan(planItems);
    return {
      objective,
      goal: goal?.objective || null,
      planItems,
      suggestedFiles: repoSnapshot.importantFiles || [],
      matchedSkills: skills.map((skill) => skill.name)
    };
  }
}

function renderPlanDocument({ title, objective, goal, planItems, createdAt, latestPlanRun, latestWorkflow, linkedWorkflow, linkedWorkflowArtifacts }) {
  return renderArtifactDocument({
    title,
    metadata: [
      `Generated at: ${createdAt}`,
      `Objective: ${objective}`,
      `Active goal: ${goal ? goal.objective : "(none)"}`,
      `Workflow: ${linkedWorkflow ? `${linkedWorkflow.id} (${linkedWorkflow.status})` : "(none)"}`
    ],
    sections: [
      {
        title: "Plan Items",
        lines: planItems.length > 0
          ? planItems.map((item) => `- [${item.status === "completed" ? "x" : " "}] ${item.content}`)
          : ["- No plan items saved."]
      },
      {
        title: "Linked Summaries",
        lines: [
          renderLatestPlanRunSummaryLine(latestPlanRun),
          renderLatestWorkflowSummaryLine(latestWorkflow),
          linkedWorkflow
            ? `- Linked workflow reviews: ${(linkedWorkflow.reviewIds || []).length}, traces: ${(linkedWorkflow.traceIds || []).length}`
            : "- Linked workflow details: (none)",
          `- Linked workflow artifacts: ${formatObjectFieldList(linkedWorkflowArtifacts || [], "path")}`
        ]
      }
    ],
    notes: [
      "This file was generated by the coding-agent plan artifact exporter.",
      "Export a fresh artifact after changing the active plan."
    ]
  });
}

function buildSuggestedPlanItems({ objective, repoSnapshot }) {
  const importantFiles = (repoSnapshot.importantFiles || []).slice(0, 5);
  const firstFile = importantFiles[0] || "README.md";
  return [
    {
      content: `Inspect the existing implementation context for: ${objective}. Start with ${firstFile}.`,
      status: "completed"
    },
    {
      content: `Map the files and modules to change. Candidate files: ${importantFiles.join(", ") || "project files to be discovered"}.`,
      status: "pending"
    },
    {
      content: `Implement the required code changes for: ${objective}. Keep edits narrow and aligned to the mapped files.`,
      status: "pending"
    },
    {
      content: "Run verification commands and confirm the changed behavior with concrete output.",
      status: "pending"
    },
    {
      content: "Review the resulting implementation, note risks, and export the plan artifact if it should be shared.",
      status: "pending"
    }
  ];
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
